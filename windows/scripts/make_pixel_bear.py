"""Writes the app icon at 32 x 32 for the CLI start banner.

Run with Pillow installed:
  python windows/scripts/make_pixel_bear.py           writes windows/src/Mason.Cli/PixelBear.cs
  python windows/scripts/make_pixel_bear.py --swift   writes macos/Sources/mason/PixelBear.swift
Each terminal row draws two pixel rows with the upper half block, so 32 pixels make 16 rows.
"""
import sys
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ICON = ROOT / "src" / "MasonAgent" / "Assets" / "Brand" / "icon.png"
OUT = ROOT / "src" / "Mason.Cli" / "PixelBear.cs"
SWIFT_OUT = ROOT.parent / "macos" / "Sources" / "mason" / "PixelBear.swift"
SIZE = 32

image = Image.open(ICON).convert("RGBA").resize((SIZE, SIZE), Image.LANCZOS)
rows = []
for y in range(SIZE):
    cells = []
    for x in range(SIZE):
        r, g, b, a = image.getpixel((x, y))
        cells.append("......" if a < 110 else f"{r:02X}{g:02X}{b:02X}")
    rows.append('        "' + "".join(cells) + '",')

if "--swift" in sys.argv[1:]:
    SWIFT_OUT.write_text(
        "// Generated by windows/scripts/make_pixel_bear.py --swift from the app icon. Do not edit by hand.\n"
        "/// The app icon at 32 x 32 pixels: six hex digits per pixel, \"......\" where it is transparent.\n"
        "enum PixelBear {\n"
        f"    static let size = {SIZE}\n"
        "    static let pixels: [String] = [\n" + "\n".join(rows) + "\n    ]\n}\n",
        encoding="utf8", newline="\n")
    print(SWIFT_OUT)
else:
    OUT.write_text(
        "// Generated by windows/scripts/make_pixel_bear.py from the app icon. Do not edit by hand.\n"
        "/// <summary>The app icon at 32 x 32 pixels: six hex digits per pixel, \"......\" where it is transparent.</summary>\n"
        "internal static class PixelBear\n{\n"
        f"    public const int Size = {SIZE};\n"
        "    public static readonly string[] Pixels =\n    [\n" + "\n".join(rows) + "\n    ];\n}\n",
        encoding="utf8", newline="\n")
    print(OUT)
