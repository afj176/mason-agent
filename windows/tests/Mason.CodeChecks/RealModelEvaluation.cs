        File.WriteAllText(Path.Combine(root,"request.txt"),request);
        await new CodeEngine(store, new CodeLocalModel(profile, "", reasoning, b => Console.WriteLine("BUDGET " + b)), Review, Changed).Run(session, request, deadline.Token);
        var independent = await CodeCommand.Run(python, ["-c", Acceptance, workspace], workspace, default, autoSandbox ? workspace : null);
