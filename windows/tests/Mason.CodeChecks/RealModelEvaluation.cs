        var report = new { Model = model, Endpoint = endpoint, Reasoning = reasoning, AutoSandbox = autoSandbox, Shell=session.Shell.ToString(),AgentUsedSelectedShell=selectedShellUsed, session.Id, session.State, session.Detail, BaselineExit = baseline.ExitCode, AgentTests = session.Activities.Where(a => a.Tool is "run_command" or "run_shell"), IndependentExit = independent.ExitCode, IndependentOutput = independent.Output, FinalTestsExit = finalTests.ExitCode, FinalTestsOutput = finalTests.Output, AgentRanTests=testsRun, ReadmeOpened=readmeOpened, AddedRegressionCoverage=regressionCoverage, UnrelatedPreserved = untouched, Reviews = reviews, Changes = session.Changes.Select(c => new { c.Path, c.AfterHash }), Git = await CodeGit.Inspect(workspace, default) };
