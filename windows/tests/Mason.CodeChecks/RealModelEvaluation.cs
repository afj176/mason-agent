    public static async Task Run(string endpoint, string model, string destination, string reasoning = "off", bool autoSandbox = false,bool gitBash=false)
    {
        var workspace = Prepare(destination); var root = Path.GetFullPath(destination);
        var python = CodeCommand.ResolveExecutable("python.exe", workspace);
        var git = CodeCommand.ResolveExecutable("git.exe", workspace);
        if(gitBash)
        {
            var bash=CodeShells.Find(CodeShellKind.GitBash)??throw new Exception("Git Bash is required.");Directory.CreateDirectory(Path.Combine(workspace,".qa-hooks"));
            foreach(var script in new[]{"git -c init.templateDir= -c core.hooksPath=.qa-hooks init -b feature/cursor-pagination","git -c core.hooksPath=.qa-hooks add .","git -c core.hooksPath=.qa-hooks -c user.name='Mason QA' -c user.email=qa@localhost commit -m 'Evaluation baseline'"})
            {var result=await CodeCommand.Run(bash,["--noprofile","--norc","-c",script],workspace,default,workspace);if(result.ExitCode!=0)throw new Exception("Sandboxed fixture setup failed: "+result.Output);}
        }
        else foreach (var args in new[] { new[] { "init", "-b", "feature/cursor-pagination" }, new[] { "add", "." }, new[] { "-c", "user.name=Mason QA", "-c", "user.email=qa@localhost", "commit", "-m", "Evaluation baseline" } })
        { var result = await CodeCommand.Run(git, args, workspace, default); if (result.ExitCode != 0) throw new Exception(result.Output); }
        var baseline = await CodeCommand.Run(python, ["-m", "unittest", "discover", "-s", "tests", "-v"], workspace, default,autoSandbox?workspace:null);
        if (baseline.ExitCode != 0) throw new Exception("Invalid evaluation baseline: " + baseline.Output);
        File.WriteAllText(Path.Combine(root, "baseline.txt"), baseline.Output);
        using var store = new CodeStore(Path.Combine(root, "profile")); var session = store.New(workspace);
        var profile = new AiEndpointProfile { Name = model + " · real model evaluation", Model = model, Endpoint = endpoint, ManagedCapability = AiCapability.Chat };
        session.Model = profile.Id; session.Permission = autoSandbox ? CodePermission.Auto : CodePermission.WorkspaceEdits; session.Reasoning = reasoning;
        if(gitBash){session.Shell=CodeShellKind.GitBash;session.ShellExecutable=CodeShells.Find(CodeShellKind.GitBash);store.Save(session);}
        File.WriteAllText(Path.Combine(root, "profile", "ai-connections.json"), JsonSerializer.Serialize(new[] { profile }, new JsonSerializerOptions { WriteIndented = true }));
        var reviews = new List<object>();
        async Task<bool> Review(CodeApproval approval, CancellationToken ct)
        {
            // This evaluation policy approves only the exact documented test runner. Other commands remain denied.
            if(autoSandbox)throw new InvalidOperationException("Auto unexpectedly requested an approval; evaluation stopped rather than silently approving it.");
            var pending = session.Activities.Last(); bool allowed = false;
            if (pending.Tool == "run_command")
            {
                using var json = JsonDocument.Parse(pending.Arguments); var a = json.RootElement;
                var executable = CodeCommand.ResolveExecutable(a.GetProperty("executable").GetString()!, workspace);
                var argv = a.GetProperty("arguments").EnumerateArray().Select(v => v.GetString()).ToArray();
                allowed = executable.Equals(python, StringComparison.OrdinalIgnoreCase) && a.GetProperty("directory").GetString() == "." && argv.SequenceEqual(new[] { "-m", "unittest", "discover", "-s", "tests", "-v" });
            }
            reviews.Add(new { approval.Tool, approval.Description, Allowed = allowed, Policy = "exact fixture unittest command" });
            Console.WriteLine("REVIEW " + (allowed ? "ALLOW " : "DENY ") + approval.Description); await Task.CompletedTask; return allowed;
        }
        int seen = 0; string detail = "";
        void Changed()
        {
            foreach (var turn in session.Turns.Skip(seen)) if (turn.Role == "assistant" && turn.Text.Length > 0) Console.WriteLine("AGENT " + turn.Text);
