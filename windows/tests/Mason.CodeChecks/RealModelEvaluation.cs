        bool untouched = File.ReadAllText(Path.Combine(workspace, "unrelated.txt")) == "Preserve this exact user-owned content.\n";
        bool testsRun=session.Activities.Any(a=>(a.Tool is "run_command" or "run_shell")&&a.State=="Completed"&&a.Arguments.Contains("unittest",StringComparison.Ordinal)&&a.Result.Contains("Ran ",StringComparison.Ordinal));
        bool selectedShellUsed=!gitBash||session.Activities.Any(a=>a.Tool=="run_shell"&&a.State=="Completed"&&a.Arguments.Contains("unittest",StringComparison.Ordinal)&&a.Result.Contains("Ran ",StringComparison.Ordinal));
