        Add optional cursor to list_products and pass it through handle(query). Keep the existing positional limit/offset API, items and total fields, ordering and legacy tests working.
        Responses must include next_cursor: an opaque URL-safe string when another page exists, otherwise null. A cursor identifies the last returned product and resumes after it. Cursor takes precedence over offset (even a malformed offset). Malformed, empty, tampered and nonexistent-product cursors must produce ValueError in the service and HTTP 400 with a nonempty error in handle. Tokens generated by your implementation must round trip for varying page sizes, including the last page. Preserve limit validation.
        Malformed includes non-alphabet characters inserted anywhere in a valid cursor, including prepended or appended punctuation. Preserve legitimate base64 padding if your encoding uses it.
        Add meaningful unittest coverage in tests, document first/next-page calls and compatibility in README, run all tests, inspect results and fix failures. Use only the Python standard library and preserve unrelated.txt. Inspect the repository before editing. Finish with a concise summary and actual test evidence. Open README.md for review.
