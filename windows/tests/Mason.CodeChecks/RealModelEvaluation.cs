        Console.WriteLine("INDEPENDENT " + independent.Output); Console.WriteLine("FINAL " + finalTests.Output);
        Console.WriteLine("REPORT " + Path.Combine(root, "report.json"));
        if (session.State != "Completed" || independent.ExitCode != 0 || finalTests.ExitCode != 0 || !untouched || !testsRun || !readmeOpened || !regressionCoverage||!selectedShellUsed) Environment.ExitCode = 1;
    }
    public const string Acceptance = """
        import sys, unittest, re
        from pathlib import Path
        workspace = Path(sys.argv.pop(1)).resolve()
        sys.path.insert(0, str(workspace))
        from catalog_service.api import handle
        from catalog_service.catalog import list_products

        class IndependentAcceptance(unittest.TestCase):
            def test_legacy(self): self.assertEqual([p['id'] for p in list_products(2,4)['items']], [5,6])
            def test_first_cursor(self):
                status, body=handle({'limit':'2'}); self.assertEqual(status,200); self.assertTrue(re.fullmatch(r'[A-Za-z0-9_.~=-]+',body['next_cursor'])); self.assertEqual(body['total'],10)
            def test_roundtrip(self):
                _,a=handle({'limit':'2'}); status,b=handle({'limit':'3','cursor':a['next_cursor']}); self.assertEqual(status,200); self.assertEqual([p['id'] for p in b['items']],[3,4,5])
            def test_walk_all(self):
                ids=[]; query={'limit':'3'}
                for _ in range(8):
                    status,body=handle(query); self.assertEqual(status,200); ids.extend(p['id'] for p in body['items'])
                    if body['next_cursor'] is None: break
                    query={'limit':'3','cursor':body['next_cursor']}
                self.assertEqual(ids,list(range(1,11))); self.assertIsNone(body['next_cursor'])
            def test_precedence(self):
                _,a=handle({'limit':'2'}); status,b=handle({'limit':'2','cursor':a['next_cursor'],'offset':'nonsense'}); self.assertEqual(status,200); self.assertEqual(b['items'][0]['id'],3)
            def test_last(self): self.assertIsNone(list_products(50)['next_cursor'])
            def test_malformed(self): self.assertEqual(handle({'cursor':'not-a-token!'})[0],400)
            def test_empty(self): self.assertEqual(handle({'cursor':''})[0],400)
            def test_tampered(self):
                _,a=handle({'limit':'2'}); token=a['next_cursor']; changed=('A' if token[0]!='A' else 'B')+token[1:]; self.assertEqual(handle({'cursor':changed})[0],400)
            def test_service_error(self):
                with self.assertRaises(ValueError): list_products(cursor='bad!')
            def test_limit_validation(self):
                for limit in ('0','51','bad'): self.assertEqual(handle({'limit':limit})[0],400)
            def test_documentation(self):
                from pathlib import Path
                text=(workspace / 'README.md').read_text().lower(); self.assertIn('cursor',text); self.assertIn('offset',text); self.assertIn('next_cursor',text)
        unittest.main()
        """;
