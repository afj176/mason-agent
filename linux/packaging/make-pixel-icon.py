"""Writes linux/cli/pixel_icon.hpp: the app icon at 32 x 32 for the mason start banner.

Run with Pillow installed: python3 linux/packaging/make-pixel-icon.py
Each terminal row draws two pixel rows with the upper half block, so 32 pixels make 16 rows.
The Windows CLI has the same picture from windows/scripts/make_pixel_bear.py.
"""
from pathlib import Path
from PIL import Image

LINUX = Path(__file__).resolve().parents[1]
ICON = LINUX / "packaging" / "site.masonagent.MasonAgent.png"
OUT = LINUX / "cli" / "pixel_icon.hpp"
SIZE = 32

image = Image.open(ICON).convert("RGBA").resize((SIZE, SIZE), Image.LANCZOS)
rows = []
for y in range(SIZE):
    cells = []
    for x in range(SIZE):
        r, g, b, a = image.getpixel((x, y))
        cells.append("......" if a < 110 else f"{r:02X}{g:02X}{b:02X}")
    rows.append('    "' + "".join(cells) + '",')

OUT.write_text(
    "// Generated by linux/packaging/make-pixel-icon.py from the app icon. Do not edit by hand.\n"
    "// The app icon at 32 x 32 pixels: six hex digits per pixel, \"......\" where it is transparent.\n"
    "#pragma once\n\n"
    "namespace pixel_icon {\n\n"
    f"inline constexpr int size = {SIZE};\n"
    "inline constexpr const char* pixels[size] = {\n" + "\n".join(rows) + "\n};\n\n"
    "}  // namespace pixel_icon\n",
    encoding="utf8", newline="\n")
print(OUT)
